"""Export everything the browser lab needs from the verified Python engine.

Output: results/lab_data.json
  cas[]  : one entry per bond length (CAS(6e,6o), STO-3G)
           energies (RHF, CCSD, CCSD(T), exact), tapered Hamiltonian, tapering map,
           ADAPT operator sequence + optimal parameters after every iteration,
           active-space integrals (for Slater-Condon SQD), wavefunction summary
  fv[]   : full-valence FV(10e,8o) at 1.098 / 1.7 / 2.1 A with a shallow ADAPT
           circuit (8 operators) for the SQD demo
  checks : reference numbers the JS engine must reproduce (self-test)
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.ccsd import ccsd_t  # noqa: E402
from src.noise import DensitySim, Estimator, NoiseModel, count_gates, zne  # noqa: E402
from src.pauli import exact_ground, hf_bitstring, op_add, op_scale, popcount, s_squared, sector_indices, to_sparse  # noqa: E402
from src.pipeline import SPIN_PENALTY  # noqa: E402
from src.pipeline import circuit_for, first_chem_acc, prepare, problems_along, run_adapt  # noqa: E402
from src.sqd import sqd_energy  # noqa: E402

GEOMS = [0.90, 1.00, 1.098, 1.20, 1.35, 1.50, 1.70, 1.90, 2.10, 2.40, 2.70, 3.00]
FV_GEOMS = [1.098, 1.70, 2.10]
FV_OPS = 8
R12 = lambda v: float(f"{v:.12g}")  # noqa: E731


def pauli_list(op):
    """[[x, z, coeff_real, coeff_imag], ...] in dict insertion order (order matters for noise placement)."""
    out = []
    for (x, z), c in op.items():
        c = complex(c)
        out.append([int(x), int(z), R12(c.real), R12(c.imag)])
    return out


def taper_info(tp):
    return {"n_full": tp.n, "n": tp.n_tapered, "keep": [int(q) for q in tp.keep], "generators": [int(g) for g in tp.generators],
            "pivots": [int(p) for p in tp.pivots], "eigs": [int(e) for e in tp.eigs], "ref_bits": int(tp.ref_bits)}


def wf_summary(pr):
    P = pr.P
    nq = 2 * P.n_orb
    idx = sector_indices(nq, P.n_alpha, P.n_beta, P.n_orb)
    Hpen = op_add(pr.H, op_scale(s_squared(P.n_orb), SPIN_PENALTY))  # singlet ground state
    _, psi = exact_ground(to_sparse(Hpen, nq), idx)
    w = np.abs(psi) ** 2
    hf = hf_bitstring(P.n_orb, P.n_alpha, P.n_beta)
    order = np.argsort(-w)[:8]
    occ = [float(sum(w[b] for b in idx if (b >> q) & 1) + sum(w[b] for b in idx if (b >> (q + P.n_orb)) & 1)) for q in range(P.n_orb)]
    return {"hf_weight": float(w[hf]), "n_over_1pct": int((w > 0.01).sum()), "occupations": [round(o, 6) for o in occ],
            "top": [[int(b), round(float(w[b]), 6)] for b in order], "sector_dim": int(len(idx))}


def problem_block(pr, res):
    P = pr.P
    return {
        "n_orb": P.n_orb, "n_alpha": P.n_alpha, "n_beta": P.n_beta, "ecore": R12(P.ecore),
        "h": [[R12(v) for v in row] for row in P.h], "g": [R12(v) for v in P.g.reshape(-1)],
        "H": pauli_list(pr.Ht), "taper": taper_info(pr.tp),
        "adapt": {
            "ops": [pauli_list(pr.pool_t[i]) for i in res.ops],
            "labels": res.labels,
            "energies": [R12(e) for e in res.energies],
            "thetas": [[R12(t) for t in th] for th in res.theta_history],
        },
    }


t_all = time.time()
pes_ref = {round(r["r"], 3): r for r in json.loads((ROOT / "results" / "pes.json").read_text())}
probs_at = problems_along(GEOMS)
out = {"meta": {"molecule": "N2", "basis": "STO-3G", "generated": time.strftime("%Y-%m-%d"),
                "note": "Generated by scripts/export_lab.py from the verified NumPy engine."},
       "cas": [], "fv": [], "checks": {}}

for r in GEOMS:
    t = time.time()
    P = probs_at[r]["cas66"]
    pr = prepare(P)
    cc = ccsd_t(P.h, P.g, P.ecore, P.n_alpha, P.n_beta)
    res = run_adapt(pr)
    ref = pes_ref[round(r, 3)]["cas66"]
    assert abs(res.energies[-1] - ref["adapt"]["final"]) < 1e-7, (r, res.energies[-1], ref["adapt"]["final"])
    k = first_chem_acc(res, pr.e_exact)
    gates = circuit_for(pr, res, k) if k else []
    block = problem_block(pr, res)
    k_half = first_chem_acc(res, pr.e_exact, thr=0.8e-3)
    block.update({"r": r, "e_rhf_full": R12(P.e_rhf_full), "hf": R12(cc["hf"]), "exact": R12(pr.e_exact),
                  "exact_lowest_any_spin": R12(pr.e_lowest_any), "s2_lowest_any_spin": round(pr.s2_lowest_any, 6),
                  "ccsd": R12(cc["ccsd"]) if cc["converged"] else None, "ccsd_t": R12(cc["ccsd_t"]) if cc["converged"] else None,
                  "k_chem_acc": k, "k_half": k_half, "gates_at_k": count_gates(gates) if k else None, "wf": wf_summary(pr),
                  "s2_final": round(res.s2[-1], 8)})
    out["cas"].append(block)
    print(f"CAS R={r}: {pr.tp.n_tapered}q, {len(res.ops)} ops, k={k}, ADAPT matches pes.json ({time.time()-t:.1f}s)", flush=True)

out["fv_curve"] = []
for r in GEOMS:
    P = probs_at[r]["fv108"]
    pr = prepare(P)
    ref = pes_ref[round(r, 3)]["fv108"]
    assert abs(ref["exact"] - pr.e_exact) < 1e-9, (r, ref["exact"], pr.e_exact)
    ad = ref.get("adapt", {})
    out["fv_curve"].append({"r": r, "exact": R12(pr.e_exact), "hf": R12(ref["hf"]), "e_rhf_full": R12(P.e_rhf_full),
                            "ccsd": R12(ref["ccsd"]) if ref["cc_converged"] else None,
                            "ccsd_t": R12(ref["ccsd_t"]) if ref["cc_converged"] else None,
                            "e_t": ref.get("e_t"), "adapt_final": R12(ad["final"]) if ad else None,
                            "k_chem_acc": ad.get("k_chem_acc"), "cx_at_k": (ad.get("circuit_at_chem_acc") or {}).get("cx"),
                            "qubits_tapered": pr.tp.n_tapered, "wf": wf_summary(pr)})
    print(f"FV curve R={r} done", flush=True)

for r in FV_GEOMS:
    t = time.time()
    P = probs_at[r]["fv108"]
    pr = prepare(P)
    res = run_adapt(pr, max_ops=FV_OPS)
    block = problem_block(pr, res)
    block.update({"r": r, "exact": R12(pr.e_exact), "wf": wf_summary(pr)})
    out["fv"].append(block)
    print(f"FV R={r}: {pr.tp.n_tapered}q, {len(res.ops)} ops ({time.time()-t:.1f}s)", flush=True)

# ---------------- reference values for the JS self-test ----------------
checks = {}
# (1) noisy energies at the default model and two sweep points, chem-acc circuits at 1.098 and 2.1
noise_ref = json.loads((ROOT / "results" / "noise.json").read_text())
checks["noise"] = []
for r in (1.098, 2.10):
    ci = next(i for i, c in enumerate(out["cas"]) if abs(c["r"] - r) < 1e-6)
    P = probs_at[r]["cas66"]
    pr = prepare(P)
    res = run_adapt(pr)
    k = first_chem_acc(res, pr.e_exact, thr=0.8e-3)  # same circuit as scripts/run_noise.py
    gates = circuit_for(pr, res, k)
    n = pr.tp.n_tapered
    sim, est = DensitySim(n), Estimator(pr.Ht, n)
    for r2 in (3e-3, 1e-4, 1e-5):
        nm = NoiseModel(r2=r2, r1=r2 / 12, p_ro=1.5e-2)
        rhos = {s: sim.run(gates, pr.tp.ref_bits, nm, fold=s) for s in (1, 3, 5)}
        raw = est.energy(rhos[1], p_ro=nm.p_ro)
        rem = [est.energy(rhos[s], p_ro=nm.p_ro, rem=True) for s in (1, 3, 5)]
        checks["noise"].append({"cas_index": ci, "k": k, "r2": r2, "r1": r2 / 12, "p_ro": 1.5e-2, "raw": raw, "rem": rem[0],
                                "zne_lin": zne([1, 3], rem[:2], "linear"), "zne_rich": zne([1, 3, 5], rem, "richardson")})
    print(f"noise refs R={r} done", flush=True)
# cross-check against the stored ablation (same code path)
eq = next(c for c in checks["noise"] if abs(out["cas"][c["cas_index"]]["r"] - 1.098) < 1e-6 and c["r2"] == 3e-3)
assert abs(1e3 * (eq["raw"] - out["cas"][eq["cas_index"]]["exact"]) - noise_ref["1.098"]["ablation"]["raw"]["err_mHa"]) < 1e-6

# (2) Slater-Condon subspace energies on fixed determinant sets
rng = np.random.default_rng(3)
checks["subspace"] = []
for kind, blocks in (("cas", out["cas"]), ("fv", out["fv"])):
    for bi in ([2, 8] if kind == "cas" else [2]):
        b = blocks[bi]
        P = probs_at[b["r"]]["cas66" if kind == "cas" else "fv108"]
        pr = prepare(P)
        n_orb = P.n_orb
        Hs = to_sparse(pr.H, 2 * n_orb).tocsr()
        idx = sector_indices(2 * n_orb, P.n_alpha, P.n_beta, n_orb)
        amask = (1 << n_orb) - 1
        a_strings = sorted({int(v) & amask for v in idx})
        for m in (3, 8, len(a_strings)):
            pick = sorted(rng.choice(a_strings, size=min(m, len(a_strings)), replace=False).tolist())
            hfa = (1 << P.n_alpha) - 1
            if hfa not in pick:
                pick[0] = hfa
            pick = sorted(set(pick))
            fake = np.array([a | (a << n_orb) for a in pick], dtype=np.int64)
            e, dim, _ = sqd_energy(Hs, fake, n_orb, P.n_alpha, P.n_beta, recover=False)
            checks["subspace"].append({"kind": kind, "index": bi, "strings": pick, "energy": e, "dim": dim})
print("subspace refs done", flush=True)
out["checks"] = checks

path = ROOT / "results" / "lab_data.json"
path.write_text(json.dumps(out, separators=(",", ":")))
print(f"saved {path} ({path.stat().st_size/1e6:.2f} MB) in {time.time()-t_all:.0f}s")
